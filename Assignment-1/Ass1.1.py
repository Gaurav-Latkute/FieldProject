# Que1. Write a program to input two numbers and display their sum, difference, product, and quotient.

# Enter Two Numbrers
num1 = float(input("Enter First Number:- "))
num2 = float(input("Enter Second Number:- "))

# Calculations 
sum = num1 + num2
difference = num1 - num2
product = num1 * num2
division = num1 / num2

# Display Result
print("\nSum is:- ", sum)
print("Difference is:- ", difference)
print("Product is:- ", product)
print("Division is:- ", division)
